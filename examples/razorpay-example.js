import dotenv from 'dotenv';
import crypto from 'node:crypto';
import { createPaymentProvider, IntegrationError, ValidationError } from '../src/index.js';

// Load environment variables from .env file
dotenv.config();

/**
 * Example demonstrating how to use the Razorpay provider inside an Express / MERN backend.
 */
async function runExample() {
  console.log('=== Razorpay Provider Example ===\n');

  // 1. Initialize Razorpay provider using factory
  // Note: Replace with process.env.RAZORPAY_KEY_ID & process.env.RAZORPAY_KEY_SECRET in production
  const keyId = process.env.RAZORPAY_KEY_ID || 'rzp_test_sampleKeyId123';
  const keySecret = process.env.RAZORPAY_KEY_SECRET || 'sampleKeySecret456';
  const webhookSecret = process.env.RAZORPAY_WEBHOOK_SECRET || 'sampleWebhookSecret789';

  const payment = createPaymentProvider({
    provider: 'razorpay',
    keyId,
    keySecret,
    webhookSecret
  });

  console.log(`Initialized provider: ${payment.name}`);

  // 2. Creating an order (e.g. in Express POST /api/payments/create-order)
  console.log('\n--- 1. Creating an Order ---');
  try {
    // IMPORTANT: Amount must strictly be passed in the smallest currency sub-unit.
    // For INR: ₹10 = 1000 paise, ₹499 = 49900 paise.
    const orderPayload = {
      amount: 1000, // 1000 paise = ₹10.00
      currency: 'INR',
      receipt: `receipt_order_${Date.now()}`,
      notes: {
        userId: 'user_mern_101',
        courseId: 'mern_advanced_bootcamp'
      }
    };

    console.log('Creating order with payload:', orderPayload);

    // In a real environment with live credentials, this calls Razorpay API:
    // const orderResponse = await payment.createOrder(orderPayload);
    // console.log('Order created response:', orderResponse);

    console.log('(Skipped live API call in example runner to prevent network error with placeholder keys)');
  } catch (error) {
    if (error instanceof ValidationError) {
      console.error('Validation failed:', error.toJSON());
    } else if (error instanceof IntegrationError) {
      console.error('Provider error:', error.toJSON());
    } else {
      console.error('Unexpected error:', error);
    }
  }

  // 3. Verifying a payment signature (e.g. in Express POST /api/payments/verify)
  console.log('\n--- 2. Verifying Payment Signature (Cryptographic) ---');
  try {
    const mockOrderId = 'order_DAvDGH9L1A4G5c';
    const mockPaymentId = 'pay_DAvJ6qW4m8kX9Y';

    // Signature generated by Razorpay checkout using keySecret
    const validSignature = crypto
      .createHmac('sha256', keySecret)
      .update(`${mockOrderId}|${mockPaymentId}`)
      .digest('hex');

    // Verification call
    const verificationResult = await payment.verifyPayment({
      razorpayOrderId: mockOrderId,
      razorpayPaymentId: mockPaymentId,
      razorpaySignature: validSignature
    });

    console.log('Valid Signature Verification Result:', verificationResult);

    // Example with tampered / invalid signature
    const invalidVerificationResult = await payment.verifyPayment({
      razorpayOrderId: mockOrderId,
      razorpayPaymentId: mockPaymentId,
      razorpaySignature: 'tampered_invalid_signature_xyz'
    });

    console.log('Invalid Signature Verification Result:', invalidVerificationResult);
  } catch (error) {
    console.error('Verification error:', error);
  }

  // 4. Verifying Webhook Signature (e.g. in Express POST /api/webhooks/razorpay)
  console.log('\n--- 3. Verifying Webhook Signature ---');
  try {
    // Webhook verification MUST operate on the exact raw string or Buffer from req.body
    const rawWebhookBody = JSON.stringify({
      event: 'payment.captured',
      payload: {
        payment: {
          entity: {
            id: 'pay_DAvJ6qW4m8kX9Y',
            amount: 1000,
            currency: 'INR',
            status: 'captured'
          }
        }
      }
    });

    const webhookSignature = crypto
      .createHmac('sha256', webhookSecret)
      .update(rawWebhookBody)
      .digest('hex');

    const webhookResult = await payment.verifyWebhook({
      payload: rawWebhookBody, // Pass raw request body (unmodified)
      signature: webhookSignature
    });

    console.log('Webhook Verification Result:', webhookResult);
  } catch (error) {
    console.error('Webhook verification error:', error);
  }

  console.log('\n=== Example Run Complete ===');
}

runExample().catch(console.error);
