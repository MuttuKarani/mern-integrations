/**
 * Express Router Template Generator for mern-integrations CLI
 */

export function generateExpressRoutesTemplate(options = {}) {
  const payments = Array.isArray(options.payments) ? options.payments : [];
  const middlewares = Array.isArray(options.middlewares) ? options.middlewares : [];
  const hasIdempotency = middlewares.includes('idempotency');
  const hasWebhookNormalizer = middlewares.includes('webhook-normalizer');

  const imports = ["import { Router } from 'express';"];
  const mernImports = [];
  const configImports = [];
  const ctrlImports = [];
  const routeDefinitions = [];

  if (hasIdempotency) {
    mernImports.push('idempotencyMiddleware');
    configImports.push('idempotencyStore');
  }

  if (hasWebhookNormalizer) {
    mernImports.push('rawBodyMiddleware');
    mernImports.push('createWebhookNormalizer');
  }

  // Payments
  if (payments.length > 0) {
    ctrlImports.push("import * as paymentCtrl from './controllers/payment.controller.js';");
    payments.forEach((p) => configImports.push(p));

    const idempotencyWrapper = hasIdempotency ? 'idempotencyMiddleware({ store: idempotencyStore }), ' : '';
    routeDefinitions.push(`
// --- Payments Endpoints ---
router.post('/payments/create-order', ${idempotencyWrapper}paymentCtrl.createOrder);
router.post('/payments/verify', paymentCtrl.verifyPayment);
router.post('/payments/refund', paymentCtrl.refundPayment);`);
  }

  // Email
  if (options.email) {
    ctrlImports.push("import * as emailCtrl from './controllers/email.controller.js';");
    routeDefinitions.push(`
// --- Email Endpoints ---
router.post('/email/send', emailCtrl.sendEmail);`);
  }

  // SMS
  if (options.sms) {
    ctrlImports.push("import * as smsCtrl from './controllers/sms.controller.js';");
    routeDefinitions.push(`
// --- SMS / OTP Endpoints ---
router.post('/sms/send-otp', smsCtrl.sendOtp);
router.post('/sms/verify-otp', smsCtrl.verifyOtp);
router.post('/sms/send-message', smsCtrl.sendMessage);`);
  }

  // Storage
  if (options.storage) {
    ctrlImports.push("import * as storageCtrl from './controllers/storage.controller.js';");
    routeDefinitions.push(`
// --- Storage Endpoints ---
router.post('/storage/upload-url', storageCtrl.getUploadUrl);
router.delete('/storage/delete', storageCtrl.deleteFile);`);
  }

  // Webhooks
  if (payments.length > 0 && hasWebhookNormalizer) {
    ctrlImports.push("import * as webhookCtrl from './controllers/webhook.controller.js';");
    const primaryPayment = payments[0];
    routeDefinitions.push(`
// --- Unified Webhook Endpoint ---
// Note: rawBodyMiddleware() captures raw HTTP buffer for cryptographic HMAC verification
router.post(
  '/webhooks/${primaryPayment}',
  rawBodyMiddleware(),
  createWebhookNormalizer({
    provider: '${primaryPayment}',
    providerInstance: ${primaryPayment},
    verifySignature: true
  }),
  webhookCtrl.handleWebhook
);`);
  }

  let code = `/**
 * Express Integration Router
 * Auto-generated by: npx mern-integrations init
 */

${imports.join('\n')}
`;

  if (mernImports.length > 0) {
    code += `import { ${mernImports.join(', ')} } from 'mern-integrations';\n`;
  }

  if (configImports.length > 0) {
    code += `import { ${configImports.join(', ')} } from './config.js';\n`;
  }

  if (ctrlImports.length > 0) {
    code += `${ctrlImports.join('\n')}\n`;
  }

  code += `
const router = Router();
${routeDefinitions.join('\n')}

export default router;
`;

  return code;
}
